"""Spark's SQL query tests, as evidence for the Spark facts (#738).

Maintainer tooling (`sverify_dev`): not in the wheel, and not part of sverify's
API. The Spark counterpart of `sverify_dev.slt`, much smaller.

Spark ships its SQL tests with their expected output at each release tag:
`sql/core/src/test/resources/sql-tests/inputs/*.sql` and the golden files
`results/*.sql.out`, generated by `SQLQueryTestSuite`. The files under
`results/` run with ANSI mode on (Spark's default since 4.0), those under
`results/nonansi/` with it off. Each case of a golden file is a query, its
schema and its output (rows, or an exception with its error class).

- `fetch` clones the tests at the tag into a cache (a sparse, blobless clone,
  about 20 MB).
- `search` lists the cases whose query matches a regex, each with its link at
  the tag, for the facts' `engine-test` provenance.
- `check` checks that every `engine-test` link of the Spark facts names a case
  of a golden file at the tag: the file exists and the range starts at a
  `-- !query` line.
- `replay` runs a golden file's queries on the local `pyspark` and compares
  their output with the file's, so the cited cases are known to hold for the
  build the probes ran on. It needs a JVM: run it on homelab (CLAUDE.md).

A replay against Lean's reference, as `sverify_dev.slt` does for DuckDB, needs
a lift of Spark's SQL, which sverify does not have; the facts cite the cases
and `sverify_dev.spark_fuzz` checks the deviations against the reference.

```bash
cd python
uv run python -m sverify_dev.spark_tests search 'try_add\\('
uv run python -m sverify_dev.spark_tests search --file postgreSQL/int4 'MIN|2147483647'
uv run python -m sverify_dev.spark_tests check
uv run python -m sverify_dev.spark_tests replay try_arithmetic nonansi/try_arithmetic
```
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from collections.abc import Iterator, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[3]
FACTS = REPO / "characterization" / "spark" / "facts"
#: The Spark release the facts are about, and its commit.
TAG = "v4.3.0"
COMMIT = "98bc0212c94705434471627068f41e374ccab143"
TESTS = "sql/core/src/test/resources/sql-tests"
CACHE = Path(os.environ.get("SVERIFY_SPARK_TESTS", Path.home() / ".cache" / "sverify" / "spark-tests"))
URL = f"https://github.com/apache/spark/blob/{TAG}/{TESTS}/"
_LINK = re.compile(
    rf"^https://github\.com/apache/spark/blob/{re.escape(TAG)}/{re.escape(TESTS)}/"
    r"(results/[^#]+\.sql\.out)#L(\d+)(?:-L(\d+))?$"
)


def fetch(tag: str = TAG, cache: Path = CACHE) -> Path:
    """The tests' directory at `tag`, cloned into `cache` on first use."""
    root = cache / tag
    if not (root / TESTS).is_dir():
        cache.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            [
                "git", "clone", "-q", "--depth", "1", "--branch", tag, "--filter=blob:none",
                "--sparse", "https://github.com/apache/spark", str(root),
            ],
            check=True,
        )  # fmt: skip
        subprocess.run(["git", "-C", str(root), "sparse-checkout", "set", TESTS], check=True)
    head = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "HEAD"], check=True, capture_output=True, text=True
    ).stdout.strip()
    if tag == TAG and head != COMMIT:
        sys.exit(f"{root} is at {head}, not {TAG} ({COMMIT})")
    return root / TESTS


@dataclass(frozen=True)
class Case:
    file: str
    """The golden file, from `sql-tests/` (`results/nonansi/cast.sql.out`)."""
    line: int
    """Its `-- !query` line."""
    end: int
    """The last line of its output."""
    query: str
    schema: str
    output: str

    @property
    def ansi(self) -> bool:
        return "/nonansi/" not in self.file

    @property
    def url(self) -> str:
        return f"{URL}{self.file}#L{self.line}-L{self.end}"

    @property
    def error(self) -> str | None:
        """The error class of an exception output, or its first line."""
        if not re.match(r"^[a-z]+(\.[a-z]+)+\.\w*(Exception|Error)\b", self.output):
            return None
        m = re.search(r'"(?:errorClass|condition)"\s*:\s*"([^"]+)"', self.output)
        return m.group(1) if m else self.output.splitlines()[0]


def _lines(path: Path) -> list[str]:
    """A file's lines, split at `\\n` only, as GitHub and grep count them (a
    golden file may hold a bare `\\r` in a string)."""
    return path.read_bytes().decode().split("\n")


def parse(path: Path, rel: str) -> list[Case]:
    """The cases of one golden file."""
    lines = _lines(path)
    starts = [i for i, s in enumerate(lines) if s == "-- !query"]
    cases = []
    for k, i in enumerate(starts):
        stop = starts[k + 1] if k + 1 < len(starts) else len(lines)
        block = lines[i + 1 : stop]
        try:
            s = block.index("-- !query schema")
            o = block.index("-- !query output")
        except ValueError:
            continue
        out = block[o + 1 :]
        while out and out[-1] == "":
            out.pop()
        end = i + 1 + o + 1 + len(out)
        cases.append(
            Case(rel, i + 1, max(end, i + 1 + o + 1), "\n".join(block[:s]),
                 "\n".join(block[s + 1 : o]), "\n".join(out))
        )  # fmt: skip
    return cases


def golden(root: Path) -> Iterator[Case]:
    """Every case of every golden file under `root/results`."""
    for path in sorted((root / "results").rglob("*.sql.out")):
        yield from parse(path, str(path.relative_to(root)))


def search(root: Path, pattern: str, file: str | None = None, output: str | None = None) -> list[Case]:
    """The cases whose query matches `pattern` (a regex, case-insensitive), in
    the golden files whose path contains `file`, whose output matches `output`."""
    q = re.compile(pattern, re.I | re.S)
    o = re.compile(output, re.S) if output else None
    return [
        c
        for c in golden(root)
        if (file is None or file in c.file)
        and q.search(c.query)
        and (o is None or o.search(c.output))
    ]


def citations(facts: Path = FACTS) -> Iterator[tuple[str, str]]:
    """Each fact's `engine-test` links: (fact id, url)."""
    for path in sorted(facts.glob("*.json")):
        doc = json.loads(path.read_text())
        for check in doc["provenance"]:
            if check["method"] != "engine-test":
                continue
            for ev in check.get("evidence", []):
                yield doc["id"], ev.get("url", "")


def check(root: Path, facts: Path = FACTS) -> list[str]:
    """Problems with the facts' `engine-test` links (empty when all hold)."""
    problems: list[str] = []
    files: dict[str, list[str]] = {}
    for fact, url in citations(facts):
        m = _LINK.match(url)
        if not m:
            problems.append(f"{fact}: not a golden file at {TAG}: {url}")
            continue
        rel, start = m.group(1), int(m.group(2))
        end = int(m.group(3) or start)
        if rel not in files:
            path = root / rel
            files[rel] = _lines(path) if path.is_file() else []
        lines = files[rel]
        if not lines:
            problems.append(f"{fact}: no golden file {rel}")
        elif start > len(lines) or lines[start - 1] != "-- !query":
            problems.append(f"{fact}: line {start} of {rel} starts no case: {url}")
        elif end < start or end > len(lines):
            problems.append(f"{fact}: lines {start}-{end} of {rel} out of range: {url}")
    return problems


# --- Replay on the local Spark ----------------------------------------------

#: `SQLQueryTestSuite`'s session: its time zone, and ANSI by folder.
SUITE_CONF = {
    "spark.master": "local[2]",
    "spark.driver.memory": "1g",
    "spark.ui.enabled": "false",
    "spark.sql.shuffle.partitions": "4",
    "spark.sql.session.timeZone": "America/Los_Angeles",
}


def _settings(root: Path, rel: str) -> dict[str, str]:
    """The `--SET` directives of a golden file's input, and of what it imports."""
    name = rel.removeprefix("results/").removesuffix(".out")
    path = root / "inputs" / name
    found: dict[str, str] = {}
    if not path.is_file():
        return found
    for s in path.read_text().splitlines():
        if s.startswith("--IMPORT "):
            found = {**_settings(root, f"results/{s.split()[1]}.out"), **found}
        elif s.startswith("--SET "):
            for kv in s[len("--SET ") :].split(","):
                k, _, v = kv.strip().partition("=")
                found[k] = v
    return found


def _output(spark: Any, sql: str) -> str:
    """A query's output as the golden files print it: `HiveResult`'s rows,
    or the exception's class and error class."""
    try:
        df = spark.sql(sql)
        plan = df._jdf.queryExecution().executedPlan()
        rows = spark._jvm.org.apache.spark.sql.execution.HiveResult.hiveResultString(plan)
        return "\n".join(sorted(rows.toList().mkString("\u0000").split("\u0000"))) if rows.size() else ""
    except Exception as e:  # noqa: BLE001 - every error is a result here
        cond = getattr(e, "getCondition", lambda: None)() or getattr(e, "getErrorClass", lambda: None)()
        return f"error: {cond or type(e).__name__}"


def _expected(case: Case) -> str:
    if case.error is not None:
        return f"error: {case.error}"
    return "\n".join(sorted(case.output.split("\n"))) if case.output else ""


def replay(root: Path, names: Sequence[str], only: str | None = None) -> tuple[int, list[str]]:
    """Run each golden file's queries in order on one local session (ANSI by
    folder, the file's `--SET`s) and compare outputs: the number of cases
    compared and the mismatches. Rows compare as sorted sets of lines; errors
    by error class. `only` limits the comparison to queries matching it (all
    queries still run, for the files' views)."""
    from pyspark.sql import SparkSession

    pick = re.compile(only, re.I | re.S) if only else None
    compared, bad = 0, []
    for name in names:
        rel = f"results/{name}.sql.out"
        cases = parse(root / rel, rel)
        with tempfile.TemporaryDirectory(prefix="spark-tests-") as tmp:
            b = SparkSession.builder.appName("sverify-spark-tests")
            conf = {
                **SUITE_CONF,
                "spark.sql.warehouse.dir": f"{tmp}/warehouse",
                "spark.sql.ansi.enabled": "false" if "/nonansi/" in rel else "true",
                **_settings(root, rel),
            }
            for k, v in conf.items():
                b = b.config(k, v)
            spark = b.getOrCreate()
            try:
                for c in cases:
                    got = _output(spark, c.query)
                    if pick is not None and not pick.search(c.query):
                        continue
                    if c.schema == "struct<>" and not c.output:
                        continue
                    compared += 1
                    want = _expected(c)
                    if got != want:
                        bad.append(f"{c.url}\n  {c.query}\n  golden: {want[:200]}\n  local:  {got[:200]}")
            finally:
                spark.stop()
    return compared, bad


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("search", help="list the cases whose query matches a regex")
    s.add_argument("pattern")
    s.add_argument("--file", help="only golden files whose path contains this")
    s.add_argument("--output", help="only cases whose output matches this regex")
    s.add_argument("--limit", type=int, default=60)
    sub.add_parser("check", help="check the facts' engine-test links")
    r = sub.add_parser("replay", help="replay golden files on the local Spark")
    r.add_argument("names", nargs="+", help="golden files under results/, without .sql.out")
    r.add_argument("--only", help="compare only queries matching this regex")
    args = parser.parse_args(argv)
    root = fetch()
    if args.cmd == "search":
        found = search(root, args.pattern, args.file, args.output)
        for c in found[: args.limit]:
            out = c.output if len(c.output) < 300 else c.output[:300] + " …"
            print(f"{c.url}\n  {c.query}\n  -> {c.schema}\n     {out}\n")
        print(f"{len(found)} case(s)" + (f", {args.limit} shown" if len(found) > args.limit else ""))
    elif args.cmd == "check":
        problems = check(root)
        print("\n".join(problems) or f"{sum(1 for _ in citations())} engine-test link(s) hold")
        sys.exit(1 if problems else 0)
    else:
        compared, bad = replay(root, args.names, args.only)
        print("\n".join(bad))
        print(f"{compared - len(bad)} of {compared} case(s) agree")
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
