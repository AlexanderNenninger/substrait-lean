"""The generated source of D51's `UPPER` and `LOWER`: the mapping every tier-1
engine agrees on and the two raise sets, from the probed tables
(`sverify_dev.case_tables`).

Run `python -m sverify_dev.case_mapping --write` from `python/`. It writes
`core/Sverify/Core/CaseTable.lean` (the agreed mappings and the raise sets, read by
`Text.upper`, `Text.lower` and `UnFn.issue`) and
`python/src/sverify/_case_tables.py` (the raise sets, read by the writers' guards and the
inferred preconditions). `tests/test_case_mapping.py` compares both with a fresh
generation. Without `--write` it prints the sizes.

A scalar is in a raise set when the engines map it differently: `case-differences.json`'s
`differ`, and for `LOWER` also U+03A3, whose mapping depends on its context (the final
sigma). Every other scalar has one value, the one all engines give (itself where none maps
it); the generator asserts that value is one scalar.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LEAN = ROOT / "core" / "Sverify" / "Core" / "CaseTable.lean"
PY = ROOT / "python" / "src" / "sverify" / "_case_tables.py"
ENGINES = ("duckdb", "polars", "spark")
SIGMA = 0x03A3


def tables() -> dict[str, dict[str, dict[str, str]]]:
    return {
        e: json.loads((ROOT / "engines" / e / "probes" / "case-tables.json").read_text())
        for e in ENGINES
    }


def generate() -> dict[str, dict]:
    """Per direction: `map`, the agreed mapping `{scalar: scalar}` of the scalars an
    engine maps, and `raise`, the sorted raise set."""
    t = tables()
    recorded = json.loads((ROOT / "characterization" / "case-differences.json").read_text())
    out: dict[str, dict] = {}
    for d in ("upper", "lower"):
        raised = {int(h, 16) for h in recorded[d]["differ"]} | ({SIGMA} if d == "lower" else set())
        agreed: dict[int, int] = {}
        for h in set().union(*(x[d].keys() for x in t.values())):
            c = int(h, 16)
            if c in raised:
                continue
            (v,) = {x[d].get(h, chr(c)) for x in t.values()}
            assert len(v) == 1, f"{d}(U+{h}) is {len(v)} scalars on every engine"
            agreed[c] = ord(v)
        out[d] = {"map": dict(sorted(agreed.items())), "raise": sorted(raised)}
    return out


def lean(g: dict[str, dict]) -> str:
    def arr(m: dict[int, int]) -> str:
        return "#[" + ", ".join(f"(0x{k:X}, 0x{v:X})" for k, v in m.items()) + "]"

    def lst(s: list[int]) -> str:
        return "[" + ", ".join(f"0x{c:X}" for c in s) + "]"

    return (
        "-- Generated by `python -m sverify_dev.case_mapping --write`; do not edit.\n"
        "-- Source: engines/*/probes/case-tables.json, characterization/case-differences.json (D51).\n"  # noqa: E501
        "\nnamespace Substrait.CaseTable\n\nset_option maxRecDepth 20000\n"
        "\n/-- `UPPER` of a scalar value (its code point), where DuckDB, Polars and Spark agree:\n"
        "sorted by scalar; a scalar not listed maps to itself. -/\n"
        f"def upperMap : Array (Nat × Nat) := {arr(g['upper']['map'])}\n"
        "\n/-- `LOWER` of a scalar value, as `upperMap`. -/\n"
        f"def lowerMap : Array (Nat × Nat) := {arr(g['lower']['map'])}\n"
        "\n/-- The scalar values the engines map differently under `UPPER`. -/\n"
        f"def upperRaise : List Nat := {lst(g['upper']['raise'])}\n"
        "\n/-- The scalar values the engines map differently under `LOWER`, and U+03A3\n"
        "(the final sigma: the mapping depends on the context). -/\n"
        f"def lowerRaise : List Nat := {lst(g['lower']['raise'])}\n"
        "\nend Substrait.CaseTable\n"
    )


def python(g: dict[str, dict]) -> str:
    def tup(s: list[int]) -> str:
        return "(\n" + "".join(f"    0x{c:X},\n" for c in s) + ")"

    return (
        '"""The scalar values `UPPER` and `LOWER` raise on (D51). Generated by\n'
        '`python -m sverify_dev.case_mapping --write` from the probed tables; do not edit."""\n'
        "\n"
        "from typing import Literal\n"
        "\n"
        f"UPPER_RAISE: tuple[int, ...] = {tup(g['upper']['raise'])}\n"
        f"LOWER_RAISE: tuple[int, ...] = {tup(g['lower']['raise'])}\n"
        "\n\n"
        'def raise_set(which: Literal["upper", "lower"]) -> tuple[int, ...]:\n'
        '    """The scalar values `UPPER` or `LOWER` (`which`) raises on."""\n'
        '    return UPPER_RAISE if which == "upper" else LOWER_RAISE\n'
    )


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    g = generate()
    for d, v in g.items():
        print(d, len(v["map"]), "agreed;", len(v["raise"]), "raise", file=sys.stderr)
    if args.write:
        LEAN.write_text(lean(g))
        PY.write_text(python(g))


if __name__ == "__main__":
    main()
