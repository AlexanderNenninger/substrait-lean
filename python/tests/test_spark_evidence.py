@pytest.fixture
def tests_root(tmp_path):
    (tmp_path / "results" / "nonansi").mkdir(parents=True)
    (tmp_path / "results" / "ops.sql.out").write_bytes(GOLDEN.encode())
    (tmp_path / "results" / "nonansi" / "ops.sql.out").write_bytes(GOLDEN.encode())
    return tmp_path


def test_parse_reads_cases_and_errors(tests_root):
    cases = st.parse(tests_root / "results" / "ops.sql.out", "results/ops.sql.out")
    assert [c.query for c in cases] == ["SELECT 5 div 2", "SELECT 1 / 0", "SELECT 'a\rb'"]
    assert [c.line for c in cases] == [2, 10, 22]
    assert cases[0].schema == "struct<(5 div 2):bigint>" and cases[0].output == "2"
    assert cases[0].error is None and cases[1].error == "DIVIDE_BY_ZERO"
    assert cases[0].ansi
    assert cases[0].url.endswith("/results/ops.sql.out#L2-L7")


def test_search_filters_by_query_file_and_output(tests_root):
    assert len(st.search(tests_root, r"\bdiv\b")) == 2
    assert len(st.search(tests_root, r"\bdiv\b", file="nonansi")) == 1
    assert len(st.search(tests_root, "SELECT", output="DIVIDE_BY_ZERO")) == 2


def test_check_flags_links_that_name_no_case(tests_root, tmp_path):
    facts = tmp_path / "facts"
    facts.mkdir()
    good, bad = st.URL + "results/ops.sql.out#L10-L20", st.URL + "results/ops.sql.out#L11-L20"
    missing = st.URL + "results/nope.sql.out#L2-L3"
    doc = {
        "id": "spark-x",
        "provenance": [
            {"method": "probe", "evidence": [{"url": bad}]},
            {"method": "engine-test", "evidence": [{"url": u} for u in (good, bad, missing)]},
        ],
    }
    (facts / "spark-x.json").write_text(json.dumps(doc))
    problems = st.check(tests_root, facts)
    assert len(problems) == 2
    assert "line 11" in problems[0] and "no golden file" in problems[1]


def test_java_double_text():
    cases = {5e-324: "4.9E-324", 1e20: "1.0E20", 1e-5: "1.0E-5", 0.001: "0.001", 1e7: "1.0E7",
             123456789.0: "1.23456789E8", -0.0: "-0.0", 100.0: "100.0"}  # fmt: skip
    assert {x: fz._java_double(x) for x in cases} == cases


def test_sum_double_follows_slices():
    # In input order, 1 then 1 then 1e16 keeps both ones; 1e16 first loses them.
    assert fz._sum_double([[1.0, 1.0, 1e16]]) == [1e16 + 2]
    assert fz._sum_double([[1e16, 1.0, 1.0]]) == [1e16]
    # Two slices: each summed in order, the partials merged in either order.
    assert set(fz._sum_double([[1e16, 1.0], [1.0, 1.0]])) == {1e16 + 2}
    assert fz._sum_double([[None], []]) == [None]


def test_models_of_integer_facts():
    div = next(e for e in fz._int_divide()[0].exprs if e.spark == "a div b").model
    assert div((-128, -1), True) == 128
    assert div((7, 0), True) == fz.Raise("DIVIDE_BY_ZERO") and div((7, 0), False) is None
    assert fz._java_shift("<<", -8, 33, 32) == -16 and fz._java_shift("<<", -8, -1, 32) == 0
    assert fz._substr_model("héllo", 0, 2) == "hé"
    assert fz._substr_model("héllo", -6, 2) == "h"


def test_every_target_names_a_spark_fact():
    known = {p.stem for p in (fz.OUT.parent / "facts").glob("spark-*.json")}
    for ts in fz.targets().values():
        for t in ts:
            assert t.fact in known
