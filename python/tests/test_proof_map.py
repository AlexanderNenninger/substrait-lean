"""`docs/proofs.md`, the map of the proofs (#733), matches the Lean project.

Every Lean module has its line, every theorem the guarantees table names
exists, and every generated module says so in its header and says how to
regenerate it.
"""

import re
from pathlib import Path

import pytest

from _repo import needs_repo

# The Wheels workflow runs a copy of `tests` without the docs or the Lean sources.
pytestmark = needs_repo

ROOT = Path(__file__).resolve().parents[2]
MAP_PATH = ROOT / "docs" / "proofs.md"
MAP = MAP_PATH.read_text() if MAP_PATH.is_file() else ""

GENERATED_DIRS = [
    ROOT / "SubstraitLean" / "LoweringDuckDB" / "On",
    ROOT / "SubstraitLean" / "LiftDuckDB" / "Duckdb",
    ROOT / "SubstraitLean" / "LiftDuckDB" / "Reference",
]
GENERATED = [p for d in GENERATED_DIRS for p in sorted(d.glob("*.lean"))]
CACHES = [ROOT / "SubstraitLean" / "LoweringCache.lean", ROOT / "SubstraitLean" / "LiftCache.lean"]


def _modules() -> list[Path]:
    lean = [
        *(ROOT / "SubstraitLean").rglob("*.lean"),
        *(ROOT / "float-bounds" / "FloatBounds").glob("*.lean"),
    ]
    return sorted(p for p in lean if not any(d in p.parents for d in GENERATED_DIRS))


def _section(title: str) -> str:
    start = MAP.index(f"## {title}")
    end = MAP.find("\n## ", start + 1)
    return MAP[start : end if end != -1 else None]


@pytest.mark.parametrize("module", _modules(), ids=lambda p: str(p.relative_to(ROOT)))
def test_every_module_has_a_line(module):
    rel = module.relative_to(
        ROOT / ("float-bounds/FloatBounds" if "float-bounds" in module.parts else "SubstraitLean")
    )
    assert f"`{rel.as_posix()}`" in _section("The modules"), f"{rel} is missing from docs/proofs.md"


def test_generated_globs_have_lines():
    modules = _section("The modules")
    for glob in [
        "LoweringDuckDB/On/*.lean",
        "LiftDuckDB/Duckdb/*.lean",
        "LiftDuckDB/Reference/*.lean",
    ]:
        assert f"`{glob}`" in modules


def _theorems() -> set[str]:
    """Every theorem's name as declared, and with the namespaces it is declared
    in (`Knowledge.contract_sound`), the project's root `Substrait` left out."""
    names = set()
    for p in [
        *(ROOT / "SubstraitLean").rglob("*.lean"),
        *(ROOT / "float-bounds" / "FloatBounds").glob("*.lean"),
    ]:
        spaces: list[str] = []
        for line in p.read_text().splitlines():
            if m := re.match(r"^namespace (\S+)", line):
                spaces.append(m.group(1))
            elif (m := re.match(r"^end (\S+)", line)) and spaces and spaces[-1] == m.group(1):
                spaces.pop()
            elif m := re.match(r"^(?:private )?(?:theorem|lemma) ([^\s({:]+)", line):
                names.add(m.group(1))
                prefix = ".".join(n for n in spaces if n != "Substrait")
                if prefix:
                    names.add(f"{prefix}.{m.group(1)}")
    return names


def test_named_theorems_exist():
    table = _section("The guarantees and their theorems")
    known = _theorems()
    named = set()
    for row in table.splitlines():
        cells = row.split(" | ")  # guarantee, layer, theorems, module
        if row.startswith("| ") and len(cells) == 4 and not row.startswith("| Guarantee"):
            named.update(re.findall(r"`([^`]+)`", cells[2]))
    assert len(named) > 40
    missing = sorted(n for n in named if "<" not in n and n not in known)
    assert not missing, f"docs/proofs.md names theorems the Lean project lacks: {missing}"


@pytest.mark.parametrize("module", GENERATED + CACHES, ids=lambda p: str(p.relative_to(ROOT)))
def test_generated_modules_say_so(module):
    head = module.read_text()[:1200]
    assert "Generated by" in head
    assert "To regenerate" in head
    assert "do not" in head or "seeded" in head
